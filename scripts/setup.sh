#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${ROOT}/vars.nix"

# ---------- helpers ----------
ask() {
  local prompt="$1"
  local default="${2:-}"
  local var
  if [[ -n "$default" ]]; then
    read -r -p "$prompt [$default]: " var
    echo "${var:-$default}"
  else
    while true; do
      read -r -p "$prompt: " var
      [[ -n "$var" ]] && { echo "$var"; return; }
      echo "  (нельзя пустым)" >&2
    done
  fi
}

ask_yn() {
  local prompt="$1"
  local default="${2:-y}"
  local var
  read -r -p "$prompt [y/n] (default: $default): " var
  var="${var:-$default}"
  [[ "$var" =~ ^[Yy]$ ]]
}

nix_str() {
  printf '"%s"' "${1//\"/\\\"}"
}

echo "==================================="
echo "  NixOS config wizard"
echo "==================================="
echo

HOSTNAME=$(ask "Hostname" "nixos")
USERNAME=$(ask "Имя пользователя" "${USER:-user}")
TIMEZONE=$(ask "Часовой пояс (timedatectl list-timezones)" "Europe/Moscow")

echo
echo "Язык / locale (пример: en_US.UTF-8, ru_RU.UTF-8)"
LOCALE=$(ask "defaultLocale" "en_US.UTF-8")
LC_TIME=$(ask "LC_TIME (можно тот же)" "$LOCALE")

echo
KEYBOARD_LAYOUT=$(ask "Раскладка клавиатуры (us, ru, us,ru)" "us")
KEYBOARD_VARIANT=$(ask "Variant (можно пусто)" "")

echo
if ask_yn "NetworkManager" "y"; then
  USE_NM=true
else
  USE_NM=false
fi

if ask_yn "Bluetooth" "y"; then
  USE_BT=true
else
  USE_BT=false
fi

if ask_yn "Zsh как shell пользователя" "y"; then
  USE_ZSH=true
else
  USE_ZSH=false
fi

SHELL_PKG="pkgs.bash"
[[ "$USE_ZSH" == true ]] && SHELL_PKG="pkgs.zsh"

STATE_VERSION=$(ask "system.stateVersion (не меняй на уже стоящей системе)" "24.11")

cat >"$OUT" <<EOF
# Generated by scripts/setup-wizard.sh — можно править руками
{
  hostname = $(nix_str "$HOSTNAME");
  username = $(nix_str "$USERNAME");
  timeZone = $(nix_str "$TIMEZONE");
  defaultLocale = $(nix_str "$LOCALE");
  extraLocaleSettings = {
    LC_TIME = $(nix_str "$LC_TIME");
  };
  keyboardLayout = $(nix_str "$KEYBOARD_LAYOUT");
  keyboardVariant = $(nix_str "$KEYBOARD_VARIANT");
  networkManager = ${USE_NM};
  bluetooth = ${USE_BT};
  useZsh = ${USE_ZSH};
  stateVersion = $(nix_str "$STATE_VERSION");
}
EOF

echo
echo "Записано: $OUT"
echo
cat "$OUT"
echo
echo "Дальше:"
echo "  1. Проверь vars.nix"
echo "  2. sudo nixos-rebuild switch --flake .#${HOSTNAME}"
echo "     (hostname во flake должен совпадать с nixosConfigurations.<name>)"
